    internal static int GetIndex<TBlock>() where TBlock : Block => _indices[typeof(TBlock)];

    internal static void Register(IModExtensions extensions)
    {
        foreach (var entry in Entries)
        {
            extensions.Register(
                BlockExtensions.RegistryName,
                new ResourceId(BuiltInContentMod.Manifest.ModId, entry.Path),
                new BlockRegistration(entry.Factory)
            );
        }
